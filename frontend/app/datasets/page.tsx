"use client";

import * as React from "react";
import { Bar, BarChart, CartesianGrid, XAxis, YAxis } from "recharts";

import { fetchDatasetStats, type DatasetStats } from "@/lib/api";
import {
  ChartConfig,
  ChartContainer,
  ChartTooltip,
  ChartTooltipContent,
} from "@/components/ui/chart";
import { PageHeader, SectionLabel, StatCard } from "@/components/page-primitives";
import { Skeleton } from "@/components/ui/skeleton";

const chartConfig = {
  count: { label: "Examples", color: "var(--chart-1)" },
} satisfies ChartConfig;

export default function DatasetsPage() {
  const [stats, setStats] = React.useState<DatasetStats | null>(null);
  const [error, setError] = React.useState(false);

  React.useEffect(() => {
    fetchDatasetStats()
      .then(setStats)
      .catch(() => setError(true));
  }, []);

  if (error) {
    return (
      <div>
        <PageHeader title="Datasets" subtitle="Training data for the fine-tune." />
        <p className="text-sm text-muted-foreground">Couldn&apos;t reach the backend.</p>
      </div>
    );
  }

  if (!stats) {
    return (
      <div>
        <PageHeader title="Datasets" subtitle="Training data for the fine-tune." />
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
          {Array.from({ length: 4 }).map((_, i) => (
            <Skeleton key={i} className="h-24 w-full" />
          ))}
        </div>
      </div>
    );
  }

  const trainSplit = stats.splits.find((s) => s.name === "train")?.count ?? 0;
  const trainPct = stats.total ? Math.round((trainSplit / stats.total) * 100) : 0;

  return (
    <div>
      <PageHeader
        title="Datasets"
        subtitle="resume-jd-relevance — one dataset, generated by training/prepare_dataset.py."
      />

      {!stats.available ? (
        <div className="rounded-lg border border-border bg-card p-6">
          <SectionLabel>No local splits found</SectionLabel>
          <p className="text-sm text-muted-foreground">
            The <code className="font-metric text-xs">data/processed/*.jsonl</code> files are
            git-ignored. Regenerate them:
          </p>
          <pre className="font-metric mt-3 overflow-x-auto rounded-md bg-muted p-3 text-xs">
            python training/prepare_dataset.py --input data/raw/Resume.csv --resumes 120
          </pre>
        </div>
      ) : (
        <>
          <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
            <StatCard label="Examples" value={stats.total.toLocaleString()} sub="instruction pairs" />
            <StatCard
              label="Split"
              value={stats.splits.map((s) => s.count).join(" / ")}
              sub={`train / val / test · ${trainPct}% train`}
            />
            <StatCard
              label="Mean score"
              value={stats.score_mean !== null ? stats.score_mean.toFixed(1) : "—"}
              sub="0–100 relevance label"
            />
            <StatCard label="Labels" value="synthetic" sub="Gemini as oracle" />
          </div>

          <div className="mt-4 rounded-lg border border-border bg-card p-4">
            <SectionLabel>Score distribution</SectionLabel>
            <ChartContainer config={chartConfig} className="h-56 w-full">
              <BarChart data={stats.score_histogram}>
                <CartesianGrid vertical={false} stroke="var(--border)" />
                <XAxis dataKey="bucket" tickLine={false} axisLine={false} fontSize={11} />
                <YAxis tickLine={false} axisLine={false} fontSize={11} allowDecimals={false} />
                <ChartTooltip content={<ChartTooltipContent />} />
                <Bar dataKey="count" fill="var(--color-count)" radius={3} />
              </BarChart>
            </ChartContainer>
            <p className="mt-2 text-[11px] leading-relaxed text-muted-foreground">
              A healthy set spreads across all five bands. If the middle bands are
              near-empty, regenerate with the current{" "}
              <code className="font-metric">prepare_dataset.py</code>, which asks
              Gemini for JDs across the whole fit spectrum and splits stratified
              by band.
            </p>
          </div>

          <div className="mt-4 grid gap-4 lg:grid-cols-[280px_1fr]">
            <div className="rounded-lg border border-border bg-card p-4">
              <SectionLabel>Provenance</SectionLabel>
              <dl className="flex flex-col gap-2 text-xs">
                <div>
                  <dt className="label-caps">Source resumes</dt>
                  <dd className="mt-0.5">{stats.source}</dd>
                </div>
                <div>
                  <dt className="label-caps">Labeler</dt>
                  <dd className="mt-0.5">{stats.labeler}</dd>
                </div>
                <div>
                  <dt className="label-caps">Honesty note</dt>
                  <dd className="mt-0.5 text-muted-foreground">
                    Labels reflect Gemini&apos;s judgment of fit, not verified hiring
                    outcomes. The benchmark measures whether the fine-tune
                    specializes toward that signal — cheaper and faster than
                    prompting the larger model at inference.
                  </dd>
                </div>
              </dl>
            </div>

            <div className="rounded-lg border border-border bg-card p-4">
              <SectionLabel>Sample rows (train)</SectionLabel>
              <div className="flex flex-col gap-3">
                {stats.samples.map((s, i) => (
                  <div key={i} className="rounded-md border border-border/60 bg-muted/30 p-3">
                    <p className="font-mono text-[11px] leading-relaxed whitespace-pre-wrap text-muted-foreground">
                      {s.input.length > 260 ? s.input.slice(0, 260) + "…" : s.input}
                    </p>
                    <p className="font-metric mt-2 text-xs text-foreground">{s.output}</p>
                  </div>
                ))}
              </div>
            </div>
          </div>
        </>
      )}
    </div>
  );
}
